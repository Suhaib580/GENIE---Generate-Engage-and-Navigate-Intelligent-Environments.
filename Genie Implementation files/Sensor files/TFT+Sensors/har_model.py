def predict(feats):
    """Full feature list -> (class name, confidence 0..1).

    Takes the WHOLE vector har_features produces and selects FEATURE_IDX
    itself, so the caller never has to know which columns were dropped --
    getting that selection wrong on the board would silently feed the
    model the wrong numbers in the right shape.

    Confidence is a softmax over the output layer. It is NOT the
    probability the answer is right: a model shown something outside its
    training distribution can be confidently wrong. Use it to REFUSE, not
    to believe -- see CONFIDENCE_MIN.
    """
    sel = [feats[i] for i in FEATURE_IDX]
    n = len(sel)
    h = []
    for j in range(len(B1)):
        acc = B1[j]
        for i in range(n):
            acc += ((sel[i] - MEAN[i]) / SCALE[i]) * W1[i][j]
        h.append(acc if acc > 0 else 0.0)        # relu

    out = []
    for k in range(len(B2)):
        acc = B2[k]
        for j in range(len(h)):
            acc += h[j] * W2[j][k]
        out.append(acc)

    top = max(out)
    exps = [_exp(v - top) for v in out]
    total = sum(exps)
    best = 0
    for k in range(1, len(out)):
        if out[k] > out[best]:
            best = k
    return CLASSES[best], exps[best] / total


_E = 2.718281828459045


def _exp(x):
    """e**x. x is always <= 0 here -- softmax is shifted by the max.

    This was a hand-rolled Taylor series and it was WRONG. The series for
    e**x converges mathematically for every x, but numerically it suffers
    catastrophic cancellation once x is strongly negative: at x = -30 the
    intermediate terms reach about 7e11 while the true answer is 9e-14, so
    the sum is dominated by rounding error in numbers twenty-five orders
    of magnitude larger than the result.

    The observed symptom was confidences of -7.02 and 2.83 -- impossible
    for a softmax, and quietly poisoning the "refuse if unsure" rule while
    the CLASS predictions stayed perfectly correct. Exactly the kind of
    bug that survives testing because the headline number looks fine.

    `**` on floats is supported on both runtimes and is accurate.
    """
    if x < -60:
        return 0.0
    return _E ** x
